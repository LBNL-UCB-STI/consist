def __getattr__(name: str) -> Any:
    if name in _SUBMODULES:
        module = importlib.import_module(f"consist.{name}")
        globals()[name] = module
        return module

    if name in _CORE_EXPORTS:
        module_path, attr_name = _CORE_EXPORTS[name]
        module = importlib.import_module(module_path)
        val = module.__dict__[attr_name]
        globals()[name] = val
        return val

    if name in _DEPRECATED_TOP_LEVEL_EXPORTS:
        target_mod, target_attr = _DEPRECATED_TOP_LEVEL_EXPORTS[name]
        warnings.warn(
            f"Importing {name!r} from 'consist' is deprecated; use '{target_mod}.{target_attr}' instead.",
            DeprecationWarning,
            stacklevel=2,
        )
        module = importlib.import_module(target_mod)
        if target_attr in module.__dict__:
            return module.__dict__[target_attr]
        mod_getattr = module.__dict__.get("__getattr__")
        if callable(mod_getattr):
            return mod_getattr(target_attr)
        raise AttributeError(f"module {target_mod!r} has no attribute {target_attr!r}")

    raise AttributeError(f"module {__name__!r} has no attribute {name!r}")


